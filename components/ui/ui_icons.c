// Angel: P1's pictures on another order of segments (docs/pet-ram.md): meter, food, play, bathroom, discipline,
// medicine, light, attention.
static const uint8_t ANGEL_ORDER[8] = { 5, 0, 2, 4, 6, 3, 1, 7 };

const char *const *ui_icon_art(tc_model_t m, int icon)
{
    if (icon < 0 || icon > 7) return NULL;
    switch (m) {
    case TC_MODEL_P2: return icon == 3 ? UI_ICON_P2_MEDICINE : UI_ICONS[icon];
    case TC_MODEL_ANGEL: return UI_ICONS[ANGEL_ORDER[icon]];
    case TC_MODEL_MOTHRA: return icon == 4 ? UI_ICONS[6] : MOTHRA_ICONS[icon];
    default: return UI_ICONS[icon];
    }
}
