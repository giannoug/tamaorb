"""Generate components/tzdb/tzdb_table.c from posix_tz_db's zones.json.

Usage: tools/gen_tzdb.py path/to/zones.json [out.c]

Fetch zones.json once, from the pinned revision below, and do not commit it:
  curl -LO <SOURCE_URL>
posix_tz_db publishes no release tags, so the pin is a commit.
"""
